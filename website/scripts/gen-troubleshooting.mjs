// The troubleshooting page is GENERATED from the CLI's errors guide topic (the
// single source of truth, which also answers `stim guide errors <CODE>`) so the
// two can never drift. Runs as pre{build,start}; the output is gitignored.
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import errors from '../../packages/stim-cli/src/guide/errors.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'docs', 'troubleshooting.md');

// This site parses .md as MDX, which reads `<` and `{` as JSX outside a code
// span, so guide text such as `port <n>` is escaped before it lands in a
// paragraph, and heading ids use the MDX comment form Docusaurus accepts
// there ({/* #id */}) rather than the classic {#id}, which MDX cannot parse.
const escapeMdx = (text) =>
  text
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replaceAll('<', '&lt;').replaceAll('{', '&#123;')))
    .join('');

// An alias code needs its own anchor: a heading carries one id, and
// /docs/troubleshooting#STIM_WORKSPACE_COLLISION has to land on the entry that
// spells it. custom.css gives these anchors the sticky-navbar scroll margin.
const aliasAnchor = (alias) => `<a id="${alias}"></a>`;

export function buildTroubleshooting(topic) {
  const lines = [];
  let shownContext = null;
  for (const [name, section] of Object.entries(topic.sections)) {
    if (section.separator) {
      lines.push(`## ${escapeMdx(section.separator.replaceAll('---', '').trim())}`, '');
      shownContext = null;
    }
    if (section.context && section.context !== shownContext) {
      lines.push(escapeMdx(section.context), '');
      shownContext = section.context;
    }
    for (const alias of section.aliases ?? []) lines.push(aliasAnchor(alias), '');
    lines.push(`### ${[name, ...(section.aliases ?? [])].join(' / ')} {/* #${name} */}`, '');
    lines.push(escapeMdx(section.summary), '');
    lines.push('```text', section.body(), '```', '');
  }
  return `---
title: "Troubleshooting"
sidebar_position: 98
description: "Every refusal code Stim can print, generated from the CLI's own errors guide"
---

{/* GENERATED by scripts/gen-troubleshooting.mjs from ../packages/stim-cli/src/guide/errors.ts -- do not edit. */}

:::note[Command examples]

Commands use \`stim\`. If it is not installed globally, replace \`stim\` with
\`npx stim\`.

:::

${escapeMdx(topic.preamble())}

The same reference ships with the binary you are running: \`stim guide errors\`
lists the codes, \`stim guide errors <CODE>\` prints one entry. This page is
generated from that topic, so it says exactly what the CLI says.

${lines.join('\n').trim()}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(out, buildTroubleshooting(errors));
  const codes = Object.keys(errors.sections).filter((name) => name.startsWith('STIM_'));
  console.log(`troubleshooting: ${codes.length} codes -> docs/troubleshooting.md`);
}
